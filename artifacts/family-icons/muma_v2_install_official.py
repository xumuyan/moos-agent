# -*- coding: utf-8 -*-
"""Install the approved v2 candidate as the official MuMa app assets.

Candidate: A-prompt (flat terminal prompt ">_"), DeepSeek-style:
white squircle + single family-teal mark; small representations and the
in-app sidebar invert to solid teal with a white mark.
Assets keep their legacy filenames so packaging stays untouched.
"""
import hashlib
import json
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys_path = ROOT / 'artifacts' / 'family-icons'
import importlib.util
spec = importlib.util.spec_from_file_location('muma_v2_icons', sys_path / 'muma_v2_icons.py')
mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)

ASSETS = ROOT / 'apps/electron/assets'
ICONS = ROOT / 'images/muma-icon-v2'
SLUG = 'A-prompt'

def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

# white squircle + teal mark (large / app icon master)
big = mod.make_icon(SLUG, mod.marks()[SLUG], invert=False)
big.save(ICONS / 'official-1024.png')
# solid teal + white mark (small sizes / sidebar)
inv = mod.make_icon(SLUG, mod.marks()[SLUG], invert=True)

shutil.copyfile(ICONS / 'official-1024.png', ASSETS / 'moos-icon-v1.png')
inv.resize((32, 32), Image_LANCZOS := __import__('PIL.Image', fromlist=['LANCZOS']).LANCZOS).save(ASSETS / 'sidebar-icon.png')

# icns: 16/32/64 (incl. @2x) inverted for small UI surfaces; 128+ white
iconset = ICONS / 'MoMu.iconset'
if iconset.exists():
    shutil.rmtree(iconset)
iconset.mkdir()
def put(size, image, name):
    image.resize((size, size), __import__('PIL.Image', fromlist=['LANCZOS']).LANCZOS).save(iconset / name)

put(16, inv, 'icon_16x16.png')
put(32, inv, 'icon_16x16@2x.png')
put(32, inv, 'icon_32x32.png')
put(64, inv, 'icon_32x32@2x.png')
put(128, big, 'icon_128x128.png')
put(256, big, 'icon_128x128@2x.png')
put(256, big, 'icon_256x256.png')
put(512, big, 'icon_256x256@2x.png')
put(512, big, 'icon_512x512.png')
put(1024, big, 'icon_512x512@2x.png')
subprocess.run(['iconutil', '-c', 'icns', str(iconset), '-o', str(ASSETS / 'moos.icns')], check=True)

manifest = {
    'name': '沐码',
    'source': 'v2 flat redesign following DeepSeek design language: white squircle, '
              'single family-teal terminal-prompt mark (A-prompt); 16-64px icns and '
              'sidebar-icon invert to solid teal; generated by '
              'artifacts/family-icons/muma_v2_icons.py, no raster-gradient source',
    'sha256': {
        'moos-icon-v1.png': sha(ASSETS / 'moos-icon-v1.png'),
        'moos.icns': sha(ASSETS / 'moos.icns'),
        'sidebar-icon.png': sha(ASSETS / 'sidebar-icon.png'),
    },
}
(ASSETS / 'brand-assets.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
print(json.dumps(manifest, ensure_ascii=False, indent=2))
